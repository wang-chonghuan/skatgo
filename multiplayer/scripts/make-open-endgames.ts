// The open-card endgames (SKATGO-110): positions from games dealt here and played by SkatZero, where it is seat 0's
// turn with three to five tricks to go — as declarer or as a defender — and, every card open and both sides playing
// their best, exactly one of seat 0's cards wins (app/src/lib/skat/tricks/exercises/open.ts proves it and works out
// the play). The games: a fixed seed, so a deal's number names the same game on every run; the course's heuristic
// bidding (always picking up the skat), SkatZero's putting away, game and card play. The puzzles were chosen by hand
// from all that qualify (PICKS: deal and moves before the position); `--all <file>` writes every one for choosing.
//
//   node --import tsx scripts/make-open-endgames.ts [deals=2000] [--all <file>]
//   node --import tsx scripts/make-open-endgames.ts --again   works out the stored puzzles' play again from their
//                                                             records, without dealing (SKATGO-111)
//
// Writes app/src/lib/skat/tricks/exercises/open-endgames.data.ts. Run once; commit it. The app's tests prove every
// puzzle again from the file.
import { createHash } from 'node:crypto'
import { writeFileSync } from 'node:fs'
import { maxBid } from '../../app/src/lib/skat/ai'
import { cardId, fullDeck, shuffle } from '../../app/src/lib/skat/cards'
import { actor, applyMove, collectTrick, deal, type Game, type Seat } from '../../app/src/lib/skat/game'
import { type OpenRecord, type StoredOpen, moveOut, recordOfOpen, solveOpen, storeOpen } from '../../app/src/lib/skat/tricks/exercises/open'
import { OPEN_STORED } from '../../app/src/lib/skat/tricks/exercises/open-endgames.data'
import { type Logged, type SeatPlan, advance, computerTurn } from '../src/computers'
import { loadPolicy } from '../src/skatzero/policy'

const DIR = new URL('../skatzero/', import.meta.url)
const OUT = new URL('../../app/src/lib/skat/tricks/exercises/open-endgames.data.ts', import.meta.url)
const SEED = 'skatgo-endgames/1'
const args = process.argv.slice(2)
const allAt = args.indexOf('--all')
const all = allAt >= 0 ? args[allAt + 1] : null
const count = Number(args.find((a, i) => /^\d+$/.test(a) && args[i - 1] !== '--all') ?? 2000)

const write = (chosen: StoredOpen[]) =>
  writeFileSync(
    OUT,
    `// Generated by multiplayer/scripts/make-open-endgames.ts (SKATGO-110) — never edit by hand; the app's tests prove
// every puzzle again from this file.
import type { StoredOpen } from './open'

export const OPEN_STORED: StoredOpen[] = ${JSON.stringify(chosen)}
`,
  )

if (args.includes('--again')) {
  write(OPEN_STORED.map((s) => storeOpen(recordOfOpen(s), solveOpen(recordOfOpen(s)))))
  console.log(`${OPEN_STORED.length} puzzles worked out again`)
  process.exit(0)
}

/** The deal's own random numbers, from the seed and its number (as make-endgames.ts deals). */
function rng(label: string) {
  let a = createHash('sha256').update(`${SEED}|${label}`).digest().readUInt32LE(0)
  return () => {
    a = (a + 0x6d2b79f5) | 0
    let t = Math.imul(a ^ (a >>> 15), 1 | a)
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}

type Candidate = { key: string; deal: number; left: number; role: string; stored: StoredOpen }

const policy = await loadPolicy(DIR)
const found: Candidate[] = []
for (let k = 0; k < count; k++) {
  const r = rng(`deal|${k}`)
  const deck = shuffle(fullDeck(), r)
  const dealer = Math.floor(r() * 3) as Seat
  const g0 = deal(dealer, deck)
  const plans = [0, 1, 2].map((seat): SeatPlan => ({ maxBid: maxBid(g0.hands[seat]), skatOrHand: () => ({ pickup: true }) }))
  const log: Logged[] = []
  try {
    await advance(g0, log, (g) => computerTurn(g, actor(g)!, plans[actor(g)!], policy), undefined, true)
  } catch {
    continue
  }
  // The game again, move by move: every place where it is seat 0's turn in the play with three to five cards left.
  let g: Game = g0
  for (let i = 0; i < log.length; i++) {
    const { move } = log[i]
    if (move.type === 'claim' || move.type === 'concede') break
    if (g.phase === 'trickEnd') g = collectTrick(g)
    g = applyMove(g, move)
    let at = g
    if (at.phase === 'trickEnd') at = collectTrick(at)
    const left = at.hands[0].length
    if (at.phase !== 'play' || actor(at) !== 0 || left < 3 || left > 5 || at.declarer === null || at.declaration?.contract.kind === 'null') continue
    const record: OpenRecord = { id: '', dealer, deck: deck.map(cardId), moves: log.slice(0, i + 1).map((l) => moveOut(l.move)) }
    try {
      const e = solveOpen(record)
      found.push({ key: `${k}:${i + 1}`, deal: k, left, role: e.role, stored: storeOpen(record, e) })
    } catch {
      // not a puzzle: decided already, no choice, or not exactly one winning card
    }
  }
}
await policy.release()

// The twenty, in the order the list climbs (deal:moves before the position): three tricks to go, then four, then
// five, declarer and defender in turn; every one asks for two to four choices on the way.
const PICKS: string[] = [
  '1014:27', '1241:27', '168:38', '1612:27', '361:27', '1202:28',
  '509:29', '1743:28', '1524:28', '1119:30', '1086:27', '1419:29', '1819:26',
  '705:23', '1773:21', '34:23', '1018:21', '533:22', '1266:41', '1352:21',
]
if (all) writeFileSync(all, found.map((c) => JSON.stringify({ key: c.key, left: c.left, role: c.role, ...c.stored })).join('\n') + '\n')
const chosen: StoredOpen[] = PICKS.map((key, i) => {
  const pick = found.find((c) => c.key === key)
  if (!pick) throw new Error(`${key} is not a puzzle`)
  return { ...pick.stored, id: `offenes-endspiel-${i + 1}` }
})
if (PICKS.length) write(chosen)
const by = (f: (c: Candidate) => boolean) => found.filter(f).length
console.log(`${found.length} puzzles in ${count} games: ` + [3, 4, 5].map((n) => `${n} left ${by((c) => c.left === n && c.role === 'declarer')} declarer / ${by((c) => c.left === n && c.role === 'defender')} defender`).join(', '))
